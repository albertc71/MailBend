#!/usr/bin/env python3
"""Generate the offline UTS #51 Annex C flag identifier table from pinned CLDR."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tools/unicode/cldr-49"
OUTPUT = ROOT / "src/unicode_tags.bend"


def identifiers():
    manifest = json.loads((DATA / "source.json").read_text())
    for path, pin in manifest["files"].items():
        raw = (DATA / Path(path).name).read_bytes()
        assert hashlib.sha256(raw).hexdigest() == pin["sha256"], path
    selected = set()
    for kind, statuses in (("subdivision", {"regular", "deprecated"}),
                           ("region", {"regular", "deprecated", "macroregion"})):
        for element in ET.parse(DATA / f"{kind}.xml").iter("id"):
            if element.attrib["idStatus"] not in statuses:
                continue
            for value in element.text.split():
                lo, sep, suffix = value.partition("~")
                hi = lo[:-len(suffix)] + suffix if sep else lo
                assert len(lo) == len(hi) and lo[:-1] == hi[:-1], value
                for end in range(ord(lo[-1]), ord(hi[-1]) + 1):
                    item = lo[:-1] + chr(end)
                    if kind == "subdivision" or re.fullmatch(r"[0-9]{3}", item):
                        assert re.fullmatch(r"[a-z0-9]{1,30}", item), item
                        selected.add(item)
    assert len(selected) == manifest["count"]
    return sorted(selected)


def render():
    groups = {}
    for value in identifiers():
        groups.setdefault(value[:2], []).append(value[2:])
    lines = ["# Generated by tools/gen-unicode-tags.py.",
             "# CLDR 49, UTS #51 Annex C validity. License and pinned sources are in",
             "# tools/unicode/cldr-49/. RGI status is not a validity requirement.",
             "", "import Base", "", "def valid(code: String) -> Bool:", "  match code:"]
    for prefix, suffixes in sorted(groups.items()):
        lines.append(f"    case SCon{{'{prefix[0]}', SCon{{'{prefix[1]}', rest}}}}:")
        tokens = ("|" + "|".join(suffixes) + "|")
        chunks = [tokens[i:i + 76] for i in range(0, len(tokens), 76)]
        lines.append("      String.contains(")
        for i, chunk in enumerate(chunks):
            lines.append("        " + json.dumps(chunk) + (" ++" if i < len(chunks) - 1 else ","))
        lines.append('        "|" ++ rest ++ "|")')
    lines += ["    case _:", "      False{}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        assert OUTPUT.read_text() == expected, "run python3 tools/gen-unicode-tags.py"
        print("Unicode tag table: 5684 pinned CLDR identifiers match")
    else:
        OUTPUT.write_text(expected)


if __name__ == "__main__":
    main()
