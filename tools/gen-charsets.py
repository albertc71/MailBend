#!/usr/bin/env python3
"""Generate the WHATWG charset label table and single-byte indexes from pinned sources."""
import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tools/whatwg-encoding"
OUTPUT = ROOT / "src/charsets.bend"
GROUPS = {
    "The Encoding": "Utf8{}",
    "Legacy single-byte encodings": None,
    "Legacy multi-byte Chinese (simplified) encodings": "MultiByte{}",
    "Legacy multi-byte Chinese (traditional) encodings": "MultiByte{}",
    "Legacy multi-byte Japanese encodings": "MultiByte{}",
    "Legacy multi-byte Korean encodings": "MultiByte{}",
}
# Recognised encodings that are not decoded, so their text reads as one
# U+FFFD. x-user-defined is left out, so its labels keep the UTF-8 fallback.
REPLACED = ("replacement", "UTF-16BE", "UTF-16LE")


# An explicit check, because python3 -O strips assert statements.
def require(ok, message):
    if not ok:
        sys.exit(f"gen-charsets: {message}")


def sources():
    manifest = json.loads((DATA / "source.json").read_text())
    texts = {}
    for name, pin in manifest["files"].items():
        raw = (DATA / name).read_bytes()
        require(hashlib.sha256(raw).hexdigest() == pin["sha256"],
                f"{name} does not match its sha256 in source.json")
        texts[name] = raw.decode("utf-8")
    return texts


# ISO-8859-8-I differs from ISO-8859-8 only in display direction, so it
# shares that index.
def index_name(encoding):
    return "iso-8859-8" if encoding == "ISO-8859-8-I" else encoding.lower()


# "koi8-r" -> "Koi8R", "iso-8859-2" -> "Iso8859_2".
def constructor(index):
    parts = index.split("-")
    name = parts[0].capitalize()
    for part in parts[1:]:
        name += ("_" if name[-1].isdigit() and part[0].isdigit() else "") + part.capitalize()
    return name


# Index lines show each code point after a tab, so U+0085 must not split them.
def pointers(text):
    table = {}
    for line in text.split("\n"):
        if line.strip() and not line.startswith("#"):
            pointer, code = line.split("\t")[:2]
            table[int(pointer)] = int(code, 16)
    require(table and set(table) <= set(range(128)),
            "a single-byte index is empty or has a pointer past 127")
    return table


def tables(texts):
    labels, indexes = [], {}
    for group in json.loads(texts["encodings.json"]):
        heading = group["heading"]
        for encoding in group["encodings"]:
            if heading in GROUPS:
                charset = GROUPS[heading]
            elif encoding["name"] in REPLACED:
                charset = "Replacement{}"
            else:
                continue
            if charset is None:
                index = index_name(encoding["name"])
                indexes.setdefault(index, pointers(texts[f"index-{index}.txt"]))
                charset = f"SingleByte{{{constructor(index)}{{}}}}"
            labels += [(label, charset) for label in encoding["labels"]]
    require(len({label for label, _ in labels}) == len(labels),
            "a label names more than one encoding")
    return labels, indexes


def render():
    labels, indexes = tables(sources())
    lines = ["# Generated by tools/gen-charsets.py from the WHATWG Encoding Standard.",
             "# Its pinned sources and license are in tools/whatwg-encoding/.",
             "", "import Base", "",
             "# A single-byte index: bytes 0x80 to 0xFF each read as one code point.",
             "type Index is Data:"]
    lines += [f"  {constructor(index)}{{}}" for index in indexes]
    lines += ["", "# How text in a labelled charset is read.", "type Charset is Data:",
              "  Utf8{}", "  SingleByte{index: Index}", "  MultiByte{}", "  Replacement{}",
              "", "type Label is Data:", "  Label{name: String, charset: Charset}"]
    for index, table in indexes.items():
        escaped = [f"\\u{{{table.get(pointer, 0xFFFD):X}}}" for pointer in range(128)]
        rows = ['"' + "".join(escaped[i:i + 16]) + '"' for i in range(0, 128, 16)]
        lines += ["", f"def {index.replace('-', '_')}() -> String:"]
        lines += [("  " if i == 0 else "    ++ ") + row for i, row in enumerate(rows)]
    lines += ["", "# The code points of bytes 0x80 to 0xFF in index i, in byte order, with",
              "# U+FFFD where the index has no entry.", "def Index.table(i: Index) -> String:",
              "  match i:"]
    for index in indexes:
        lines += [f"    case {constructor(index)}{{}}:", f"      {index.replace('-', '_')}()"]
    lines += ["", "# Every label of the encodings above, in lower case.",
              "def labels() -> List<&2, Label>:"]
    entries = [f"Label{{{json.dumps(label)}, {charset}}}" for label, charset in labels]
    lines += [("  [" if i == 0 else "   ") + entry + ("]" if i == len(entries) - 1 else ",")
              for i, entry in enumerate(entries)]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        require(OUTPUT.read_text() == expected,
                "src/charsets.bend is out of date: run python3 tools/gen-charsets.py")
        print("Charset tables: pinned WHATWG labels and single-byte indexes match")
    else:
        OUTPUT.write_text(expected)


if __name__ == "__main__":
    main()
